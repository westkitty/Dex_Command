package com.example.domain.engine

import com.example.data.local.DependencyLinkEntity
import com.example.data.local.ExecutionRecordEntity
import com.example.data.local.ProjectEntity
import com.example.data.local.WorkItemEntity
import com.example.domain.model.AgentTarget
import com.example.domain.model.EvidenceState

object PromptGenerator {

    /**
     * Generates a standalone, grounded prompt for a coding agent.
     * Strictly avoids inventing repository state or assuming tool/network/repo access.
     */
    fun generateTaskPrompt(
        agentTarget: AgentTarget,
        project: ProjectEntity,
        workItem: WorkItemEntity?,
        executionRecords: List<ExecutionRecordEntity>,
        dependencyLinks: List<DependencyLinkEntity>,
        allProjects: List<ProjectEntity>,
        allWorkItems: List<WorkItemEntity>,
        additionalOperatorNote: String = ""
    ): String {
        val verifiedRecords = executionRecords
            .filter { it.verificationStatus == EvidenceState.VERIFIED || it.verificationStatus == EvidenceState.OBSERVED }
            .sortedByDescending { it.timestamp }
            .take(4)

        val unverifiedRecords = executionRecords
            .filter { it.verificationStatus == EvidenceState.CLAIMED || it.verificationStatus == EvidenceState.UNKNOWN }
            .sortedByDescending { it.timestamp }
            .take(3)

        val unresolvedBlockers = DependencyResolver.resolveUnresolvedBlockersForProject(
            projectId = project.id,
            allLinks = dependencyLinks,
            projects = allProjects,
            workItems = allWorkItems
        )

        return buildString {
            appendLine("# STANDALONE AGENT TASK PROMPT — TARGET: ${agentTarget.displayName.uppercase()}")
            appendLine("# Generated by DEX//COMMAND (User-Initiated · Never Auto-Executed)")
            appendLine()

            appendLine("## 1. Project Identity")
            appendLine("- **Project Name:** ${project.name}")
            appendLine("- **Project ID:** `${project.id}`")
            appendLine("- **Category:** ${project.category}")
            appendLine("- **Authoritative Status:** `${project.status.label}` (Priority P${project.priority})")
            appendLine("- **Purpose:** ${project.purpose.ifBlank { project.description.ifBlank { "Not specified in control deck." } }}")
            if (project.repositoryUrl.isNotBlank()) {
                appendLine("- **Recorded Repository URL:** ${project.repositoryUrl} _(Do NOT assume write access or current branch state without inspecting directly.)_")
            } else {
                appendLine("- **Recorded Repository URL:** None recorded _(Do NOT invent a repository URL or branch state.)_")
            }
            if (project.isDemo) {
                appendLine("- **Notice:** This record is marked `[DEMO]` in DEX//COMMAND.")
            }
            appendLine()

            appendLine("## 2. Target and Scope")
            if (workItem != null) {
                appendLine("- **Target Work Item:** ${workItem.title} (`${workItem.id}`)")
                appendLine("- **Work Item Priority / Status:** P${workItem.priority} / `${workItem.status.label}` (Evidence: `${workItem.evidenceState.label}`)")
                appendLine("- **Bounded Scope:** ${workItem.description.ifBlank { workItem.title }}")
            } else {
                appendLine("- **Target Objective:** ${project.currentObjective.ifBlank { "Inspect current workspace state and propose next bounded task." }}")
                appendLine("- **Bounded Scope:** Restrict changes strictly to the objective above; do not expand scope.")
            }
            if (additionalOperatorNote.isNotBlank()) {
                appendLine("- **Operator Note:** $additionalOperatorNote")
            }
            appendLine()

            appendLine("## 3. Known Facts (Grounded — Do Not Invent Repository State)")
            appendLine("- **Last Verified Milestone:** ${project.lastVerifiedMilestone.ifBlank { "None recorded." }}")
            appendLine("- **Last Verified State Summary:** ${project.lastVerifiedStateSummary.ifBlank { "None recorded — inspect workspace directly before making changes." }}")
            if (verifiedRecords.isNotEmpty()) {
                appendLine("- **Verified / Observed Ledger Entries:**")
                verifiedRecords.forEach { rec ->
                    appendLine("  - `[${rec.verificationStatus.label}]` (${rec.toolOrAgent}): ${rec.actionAttempted} — Evidence: ${rec.evidence.ifBlank { "Recorded without attachment" }}")
                }
            }
            if (unverifiedRecords.isNotEmpty()) {
                appendLine("- **Unverified Claims (Must Be Independently Checked, Never Assumed True):**")
                unverifiedRecords.forEach { rec ->
                    appendLine("  - `[${rec.verificationStatus.label}]` (${rec.toolOrAgent}): ${rec.claim.ifBlank { rec.actionAttempted }}")
                }
            }
            if (project.knownFailures.isNotEmpty()) {
                appendLine("- **Known Failures:**")
                project.knownFailures.forEach { appendLine("  - $it") }
            }
            if (unresolvedBlockers.isNotEmpty()) {
                appendLine("- **Unresolved Blocking Dependencies:** ${unresolvedBlockers.size} active blocker(s) recorded. Verify whether blockers affect this task before editing.")
            }
            appendLine("- **Tool & Access Guardrail:** Do not assume unverified files, commits, credentials, remote access, or tool permissions exist. Confirm local repository state first.")
            appendLine()

            appendLine("## 4. Required Action")
            if (workItem != null) {
                appendLine("1. Inspect the actual workspace/files relevant to **${workItem.title}** and confirm current state against Section 3.")
                appendLine("2. Implement the minimal, clean changes required to satisfy: ${workItem.description.ifBlank { workItem.title }}.")
                appendLine("3. Run local verification commands/tests relevant to the touched scope.")
            } else {
                appendLine("1. Inspect the actual workspace state for **${project.name}**.")
                appendLine("2. Execute only the bounded objective: ${project.currentObjective.ifBlank { project.purpose }}.")
                appendLine("3. Capture verifiable command output or test results.")
            }
            appendLine()

            appendLine("## 5. Protected Behavior (Must Not Break)")
            if (project.protectedConstraints.isEmpty()) {
                appendLine("- Preserve existing public APIs, user data integrity, and passing tests.")
            } else {
                project.protectedConstraints.forEach { constraint ->
                    appendLine("- $constraint")
                }
            }
            appendLine("- Never push, force-push, delete branches/files destructively, deploy, or overwrite imported source documents without separate explicit operator authorization.")
            appendLine()

            appendLine("## 6. Validation")
            val criteria = workItem?.acceptanceCriteria.orEmpty()
            if (criteria.isEmpty()) {
                appendLine("- Provide reproducible build, test, or inspection output proving the change works.")
            } else {
                criteria.forEach { criterion ->
                    appendLine("- [ ] Verify: $criterion")
                }
            }
            appendLine("- Any validation step that could not be executed in your environment must be explicitly reported as NOT EXECUTED.")
            appendLine()

            appendLine("## 7. Stopping Conditions")
            appendLine("- STOP immediately and ask the operator if:")
            appendLine("  1. Actual repository or file state contradicts Section 3 (Known Facts).")
            appendLine("  2. An unresolved blocking dependency prevents safe completion.")
            appendLine("  3. Proceeding would violate any Protected Behavior in Section 5.")
            appendLine("  4. An open decision requires operator input:")
            if (project.openDecisions.isNotEmpty()) {
                project.openDecisions.forEach { decision ->
                    appendLine("     - Open decision: $decision")
                }
            } else {
                appendLine("     - Any architectural or destructive decision outside the bounded scope.")
            }
            appendLine()

            appendLine("## 8. Reporting Requirements")
            appendLine("Return a structured summary containing:")
            appendLine("1. **Action Attempted:** Exact files inspected/modified and commands executed.")
            appendLine("2. **Claim:** Concise statement of what was achieved.")
            appendLine("3. **Verifiable Evidence:** Exact test output, exit codes, diffs, or observed logs.")
            appendLine("4. **Proposed Evidence State:** `OBSERVED`, `CLAIMED`, or `FAILED` (Note: DEX//COMMAND reserves `VERIFIED` for independent operator confirmation).")
            appendLine("5. **Remaining Risks / Next Bounded Task:** Any unresolved gaps or follow-up work.")
        }
    }
}
