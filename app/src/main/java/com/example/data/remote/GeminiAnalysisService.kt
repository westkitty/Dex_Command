package com.example.data.remote

import android.util.Log
import com.example.data.local.ExecutionRecordEntity
import com.example.data.local.ImportedDocumentEntity
import com.example.data.local.ProjectEntity
import com.example.data.local.WorkItemEntity
import com.google.firebase.Firebase
import com.google.firebase.ai.ai
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.TimeoutCancellationException
import kotlinx.coroutines.withTimeout

private const val TAG = "GeminiAnalysisService"

/**
 * Optional Gemini integration via Firebase AI Logic (no client API key required).
 * Strictly limited to the 4 user-authorized read-only analysis roles:
 * 1. Summarizing imported project records (never mutates original content)
 * 2. Suggesting next bounded tasks
 * 3. Refining/drafting handoff prompts (never auto-executed)
 * 4. Identifying possibly inconsistent status records (never marks VERIFIED)
 */
class GeminiAnalysisService {

    private val model by lazy {
        Firebase.ai.generativeModel(modelName = "gemini-3.8-flash")
    }

    suspend fun summarizeImportedDocument(doc: ImportedDocumentEntity): Result<String> {
        val prompt = """
            You are an advisory engineering analyst inside DEX//COMMAND.
            Summarize the following imported project document concisely in Markdown bullet points.
            STRICT RULES:
            - Do NOT invent repository files, commit hashes, or tool access not stated in the document.
            - Clearly separate factual observations from unverified claims or open questions.
            - Never claim a task is VERIFIED unless explicit evidence is quoted in the document.
            
            File: ${doc.fileName} (${doc.format})
            Content:
            ${doc.rawContent.take(12000)}
        """.trimIndent()
        return runSafeInference(prompt)
    }

    suspend fun suggestNextTasks(
        project: ProjectEntity,
        workItems: List<WorkItemEntity>,
        recentRecords: List<ExecutionRecordEntity>
    ): Result<String> {
        val itemsText = workItems.joinToString("\n") {
            "- [P${it.priority} | ${it.status.label} | Evidence: ${it.evidenceState.label}] ${it.title}: ${it.description}"
        }.ifBlank { "(No work items yet)" }

        val recordsText = recentRecords.take(8).joinToString("\n") {
            "- [${it.verificationStatus.label}] ${it.toolOrAgent}: ${it.actionAttempted} | Claim: ${it.claim} | Evidence: ${it.evidence.ifBlank { "NONE" }}"
        }.ifBlank { "(No execution records yet)" }

        val prompt = """
            You are an advisory project planner inside DEX//COMMAND.
            Propose 3 concrete, bounded next tasks for this project.
            STRICT RULES:
            - Base recommendations strictly on the supplied state; do not fabricate repo structure or hidden context.
            - Highlight any unverified claims that should be verified before dependent work starts.
            - Respect all Protected Constraints.
            
            Project: ${project.name} (${project.status.label}, P${project.priority})
            Purpose: ${project.purpose}
            Current Objective: ${project.currentObjective}
            Protected Constraints: ${project.protectedConstraints.joinToString("; ").ifBlank { "None" }}
            Known Failures: ${project.knownFailures.joinToString("; ").ifBlank { "None" }}
            Open Decisions: ${project.openDecisions.joinToString("; ").ifBlank { "None" }}
            
            Work Items:
            $itemsText
            
            Recent Execution Ledger:
            $recordsText
        """.trimIndent()
        return runSafeInference(prompt)
    }

    suspend fun refineHandoffPrompt(basePrompt: String): Result<String> {
        val prompt = """
            You are refining a standalone coding-agent handoff prompt generated by DEX//COMMAND.
            Tighten clarity and operational precision while strictly preserving ALL 8 sections:
            1. Project Identity
            2. Target and Scope
            3. Known Facts
            4. Required Action
            5. Protected Behavior
            6. Validation
            7. Stopping Conditions
            8. Reporting Requirements
            
            STRICT RULES:
            - Do NOT invent any repository files, branch names, test commands, or credentials not present in the source prompt.
            - Keep the prohibition against assuming unverified claims are verified.
            - Output ONLY the refined Markdown prompt.
            
            Source Prompt:
            ${basePrompt.take(12000)}
        """.trimIndent()
        return runSafeInference(prompt)
    }

    suspend fun auditStatusInconsistencies(
        projects: List<ProjectEntity>,
        workItems: List<WorkItemEntity>,
        records: List<ExecutionRecordEntity>
    ): Result<String> {
        val snapshot = buildString {
            projects.take(20).forEach { p ->
                val pItems = workItems.filter { it.projectId == p.id }
                val pRecs = records.filter { it.projectId == p.id }.take(5)
                appendLine("PROJECT: ${p.name} | Status=${p.status.label} | Milestone='${p.lastVerifiedMilestone}'")
                pItems.forEach { w ->
                    appendLine("  WORK_ITEM: ${w.title} | Status=${w.status.label} | Evidence=${w.evidenceState.label}")
                }
                pRecs.forEach { r ->
                    appendLine("  RECORD: ${r.toolOrAgent} | Status=${r.verificationStatus.label} | AI=${r.aiGeneratedStatement} | HasEvidence=${r.evidence.isNotBlank()} | Action='${r.actionAttempted}'")
                }
            }
        }

        val prompt = """
            You are an evidence auditor inside DEX//COMMAND.
            Review the workspace records below and identify any possibly inconsistent status records,
            premature completion claims, unverified AI claims, or blocker mismatches.
            STRICT RULES:
            - Never declare any record VERIFIED yourself.
            - Cite exact project/task names from the data below only.
            - Return a concise, prioritized Markdown checklist of findings and suggested verification steps.
            
            Workspace Snapshot:
            ${snapshot.take(12000)}
        """.trimIndent()
        return runSafeInference(prompt)
    }

    private suspend fun runSafeInference(prompt: String): Result<String> {
        return try {
            val response = withTimeout(60_000L) {
                model.generateContent(prompt)
            }
            val text = response.text?.trim()
            if (!text.isNullOrBlank()) {
                Result.success(text)
            } else {
                Result.failure(IllegalStateException("Gemini returned an empty response."))
            }
        } catch (e: TimeoutCancellationException) {
            Log.e(TAG, "Gemini request timed out after 60s", e)
            Result.failure(IllegalStateException("Gemini analysis timed out after 60 seconds. Try again when online."))
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.e(TAG, "Firebase AI Logic inference failed", e)
            Result.failure(e)
        }
    }
}
